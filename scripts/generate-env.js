#!/usr/bin/env node
/* ============================================================
   BCAPrime — generate-env.js
   Build-time environment injection for the static site.

   Reads VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY from the
   process environment (exactly the names the app expects) and
   writes ./env.js so supabase-config.js can read them at runtime
   via window.__ENV — no bundler needed.

   Fallbacks: if the env vars are not set (fresh clone, local
   preview without Vercel env), env.js is written with empty
   values and supabase-config.js falls back to its built-in
   defaults, so the site always keeps working.

   Wired into: npm run build / npm run dev
   ============================================================ */
'use strict';

const fs = require('fs');
const path = require('path');

const url = String(process.env.VITE_SUPABASE_URL || '').trim();
const anonKey = String(process.env.VITE_SUPABASE_ANON_KEY || '').trim();

const out = [
  '/* ============================================================',
  '   BCAPrime — env.js (GENERATED by scripts/generate-env.js)',
  '   Do not edit by hand: run `npm run build` (or `npm run dev`)',
  '   to regenerate from VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY.',
  '   ============================================================ */',
  'window.__ENV = window.__ENV || {};',
  'window.__ENV.VITE_SUPABASE_URL = ' + JSON.stringify(url) + ';',
  'window.__ENV.VITE_SUPABASE_ANON_KEY = ' + JSON.stringify(anonKey) + ';',
  '',
].join('\n');

const target = path.join(__dirname, '..', 'env.js');
fs.writeFileSync(target, out, 'utf8');
console.info('[BCAPrime] env.js written' + (url && anonKey ? ' (from env vars)' : ' (empty — supabase-config.js fallbacks apply)'));
