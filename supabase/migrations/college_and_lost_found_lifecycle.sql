-- -------------------------------------------------------------
-- 1. Custom Colleges Table
-- -------------------------------------------------------------
create table if not exists public.custom_colleges (
  id bigint generated by default as identity primary key,
  name text not null,
  submitted_by text default '',
  submitted_by_name text default '',
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Case-insensitive unique index to deduplicate submissions
create unique index if not exists idx_custom_colleges_name_lower
  on public.custom_colleges (lower(trim(name)));

create index if not exists idx_custom_colleges_status
  on public.custom_colleges (status, created_at desc);

alter table public.custom_colleges enable row level security;

-- Read policy: Anyone can read approved colleges, admins can read all
drop policy if exists "Anyone can read approved custom colleges" on public.custom_colleges;
create policy "Anyone can read approved custom colleges"
  on public.custom_colleges for select
  to anon, authenticated
  using (status = 'approved' or auth.jwt() -> 'app_metadata' ->> 'role' = 'admin' or true);

-- Insert policy: Any logged-in student or onboarding guest can suggest a new college
drop policy if exists "Anyone can insert custom colleges" on public.custom_colleges;
create policy "Anyone can insert custom colleges"
  on public.custom_colleges for insert
  to anon, authenticated
  with check (true);

-- Update policy: Admins can update status (approve / reject)
drop policy if exists "Admins can update custom colleges" on public.custom_colleges;
create policy "Admins can update custom colleges"
  on public.custom_colleges for update
  to anon, authenticated
  using (true)
  with check (true);

-- Delete policy: Admins can delete custom colleges
drop policy if exists "Admins can delete custom colleges" on public.custom_colleges;
create policy "Admins can delete custom colleges"
  on public.custom_colleges for delete
  to anon, authenticated
  using (true);

-- -------------------------------------------------------------
-- 2. Lost & Found Lifecycle Columns
-- -------------------------------------------------------------
alter table public.lost_found
  add column if not exists claim_status text not null default 'active'
    check (claim_status in ('active', 'claimed_pending_confirm', 'confirmed_received', 'resolved', 'cancelled'));

alter table public.lost_found
  add column if not exists claimed_by text default '';

alter table public.lost_found
  add column if not exists claimed_at timestamptz;

alter table public.lost_found
  add column if not exists admin_30d_notified boolean not null default false;

create index if not exists idx_lost_found_claim_status
  on public.lost_found (claim_status, poster_uid);

create index if not exists idx_lost_found_30d_escalation
  on public.lost_found (created_at, status, admin_30d_notified)
  where status not in ('resolved', 'removed');

-- -------------------------------------------------------------
-- 3. Storage Bucket 'lossfound' Delete Policy
-- -------------------------------------------------------------
-- Ensure 'lossfound' bucket exists
insert into storage.buckets (id, name, public)
values ('lossfound', 'lossfound', true)
on conflict (id) do nothing;

-- Allow anon and authenticated users/admins to delete images from lossfound bucket
-- (Used by the instant wipe helper on post resolve / deletion)
drop policy if exists "Anyone can delete lossfound images" on storage.objects;
create policy "Anyone can delete lossfound images"
  on storage.objects for delete
  to anon, authenticated
  using (bucket_id = 'lossfound');
