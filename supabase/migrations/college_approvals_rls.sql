-- Policy 1: SELECT
-- Anyone (anon, authenticated) can view approved colleges.
-- Admin (openmailon@gmail.com or app_metadata.role='admin') can view ALL rows (pending, approved, rejected).
create policy "custom_colleges_select_policy"
  on public.custom_colleges for select
  to anon, authenticated
  using (
    status = 'approved'
    or is_approved = true
    or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
    or (auth.jwt() ->> 'email') = 'openmailon@gmail.com'
  );

-- Policy 2: INSERT
-- Any signed-in student or onboarding guest can suggest a new college (status must be 'pending').
create policy "custom_colleges_insert_policy"
  on public.custom_colleges for insert
  to anon, authenticated
  with check (
    status = 'pending'
    and (is_approved = false or is_approved is null)
  );

-- Policy 3: UPDATE
-- Admins can update college records (Approve or Reject).
