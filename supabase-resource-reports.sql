-- ============================================================
-- Resource Reports (students flag broken / incorrect resources)
-- Each report links to a specific resource ID and the user who
-- submitted it. Admins review these in the admin panel.
-- ============================================================
create table if not exists public.resource_reports (
  id bigint generated by default as identity primary key,
  resource_id bigint references public.resources (id) on delete cascade,
  resource_title text not null default '',
  reason text not null,
  details text not null default '',
  reporter_uid text not null default '',
  reporter_name text not null default '',
  reporter_email text not null default '',
  status text not null default 'open' check (status in ('open', 'reviewed', 'resolved', 'dismissed')),
  admin_note text not null default '',
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index if not exists resource_reports_resource_idx
  on public.resource_reports (resource_id);
create index if not exists resource_reports_status_idx
  on public.resource_reports (status);
create index if not exists resource_reports_created_idx
  on public.resource_reports (created_at desc);

alter table public.resource_reports enable row level security;

-- Anyone (logged-in user) can submit a report.
drop policy if exists "Anyone can submit resource reports" on public.resource_reports;
create policy "Anyone can submit resource reports"
  on public.resource_reports for insert
  to anon, authenticated
  with check (true);

-- Only admins can read all reports (users should not see other users' reports).
drop policy if exists "Admins can read resource reports" on public.resource_reports;
create policy "Admins can read resource reports"
  on public.resource_reports for select
  to authenticated
  using (auth.jwt() -> 'app_metadata' ->> 'role' = 'admin');

-- Users can read their own reports (optional — for "my reports" feature).
drop policy if exists "Users can read own reports" on public.resource_reports;
create policy "Users can read own reports"
  on public.resource_reports for select
  to anon, authenticated
  using (reporter_uid = coalesce(auth.uid()::text, ''));

-- Only admins can update reports (change status, add notes).
drop policy if exists "Admins can update resource reports" on public.resource_reports;
create policy "Admins can update resource reports"
  on public.resource_reports for update
  to authenticated
  using (auth.jwt() -> 'app_metadata' ->> 'role' = 'admin')
  with check (auth.jwt() -> 'app_metadata' ->> 'role' = 'admin');

-- Only admins can delete reports.
drop policy if exists "Admins can delete resource reports" on public.resource_reports;
create policy "Admins can delete resource reports"
  on public.resource_reports for delete
  to authenticated
  using (auth.jwt() -> 'app_metadata' ->> 'role' = 'admin');

-- Enable Realtime so admin panel gets live updates when new reports arrive.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'resource_reports'
  ) then
    alter publication supabase_realtime add table public.resource_reports;
  end if;
end $$;
