-- ============================================================
-- BCAPrime — Supabase Mock Test & MCQ System Schema
-- Tables: quizzes, questions, user_results, ai_quiz_usage
-- Features:
--   1. Full MCQ quizzes and questions with A/B/C/D + explanations
--   2. User results evaluation & progress tracking
--   3. Strict daily AI quiz generation limit tracking (max 3/day)
--   4. RLS security policies + permissions for anon, authenticated, service_role
-- ============================================================

-- 1. QUIZZES TABLE
create table if not exists public.quizzes (
  id bigint generated by default as identity primary key,
  title text not null,
  subject text not null,
  semester integer not null check (semester between 1 and 6),
  description text default '',
  total_questions integer not null default 0,
  time_limit_minutes integer not null default 15,
  difficulty text default 'medium' check (difficulty in ('easy', 'medium', 'hard')),
  is_ai_generated boolean not null default false,
  created_by text default 'admin',
  created_at timestamptz not null default now()
);

-- Index for speedy listing by semester/subject
create index if not exists idx_quizzes_sem_sub on public.quizzes (semester, subject);
create index if not exists idx_quizzes_created_by on public.quizzes (created_by);

-- 2. QUESTIONS TABLE
create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  question_text text not null,
  option_a text not null default '',
  option_b text not null default '',
  option_c text not null default '',
  option_d text not null default '',
  options jsonb default null, -- optional structured format { "A": "...", "B": "...", "C": "...", "D": "..." }
  correct_answer text not null check (correct_answer in ('A', 'B', 'C', 'D')),
  explanation text default '',
  created_at timestamptz not null default now()
);

create index if not exists idx_questions_quiz_id on public.questions (quiz_id);

-- 3. USER RESULTS TABLE
create table if not exists public.user_results (
  id bigint generated by default as identity primary key,
  user_id text not null,
  quiz_id bigint not null references public.quizzes(id) on delete cascade,
  score integer not null,
  total_questions integer not null,
  percentage numeric(5,2) not null default 0.00,
  answers jsonb not null default '[]'::jsonb, -- array of { question_id, selected, correct, is_correct }
  time_taken_seconds integer not null default 0,
  timestamp timestamptz not null default now()
);

create index if not exists idx_user_results_user on public.user_results (user_id, timestamp desc);
create index if not exists idx_user_results_quiz on public.user_results (quiz_id);

-- 4. AI QUIZ USAGE (Daily Quota Enforcement)
create table if not exists public.ai_quiz_usage (
  id bigint generated by default as identity primary key,
  user_id text not null,
  usage_date date not null default current_date,
  count integer not null default 1,
  created_at timestamptz not null default now(),
  constraint unique_user_daily_quota unique(user_id, usage_date)
);

create index if not exists idx_ai_usage_user_date on public.ai_quiz_usage (user_id, usage_date);

-- ============================================================
-- ATOMIC QUOTA MANAGEMENT FUNCTIONS
-- ============================================================

-- Function to check and atomically consume 1 AI quiz generation
create or replace function public.check_and_increment_ai_quota(
  p_user_id text,
  p_max_daily integer default 3
)
returns json
language plpgsql
security definer
as $$
declare
  v_today date := current_date;
  v_current_count integer := 0;
  v_new_count integer := 0;
  v_tomorrow timestamptz := (current_date + interval '1 day')::timestamptz;
begin
  if p_user_id is null or trim(p_user_id) = '' then
    return json_build_object(
      'allowed', false,
      'error', 'unauthorized',
      'message', 'User ID required to verify daily quota.'
    );
  end if;

  -- Select current count with row lock
  select count into v_current_count
  from public.ai_quiz_usage
  where user_id = p_user_id and usage_date = v_today
  for update;

  if not found then
    v_current_count := 0;
  end if;

  -- Check limit
  if v_current_count >= p_max_daily then
    return json_build_object(
      'allowed', false,
      'error', 'quota_exceeded',
      'current_count', v_current_count,
      'limit', p_max_daily,
      'remaining', 0,
      'reset_at', v_tomorrow,
      'message', 'Daily quota reached. You can generate up to ' || p_max_daily || ' AI mock tests per day. Quota resets at midnight.'
    );
  end if;

  -- Increment or insert
  insert into public.ai_quiz_usage (user_id, usage_date, count)
  values (p_user_id, v_today, 1)
  on conflict (user_id, usage_date)
  do update set count = public.ai_quiz_usage.count + 1
  returning count into v_new_count;

  return json_build_object(
    'allowed', true,
    'current_count', v_new_count,
    'limit', p_max_daily,
    'remaining', greatest(0, p_max_daily - v_new_count),
    'reset_at', v_tomorrow
  );
end;
$$;

-- Function to get current daily AI quota without consuming
create or replace function public.get_ai_quiz_quota(
  p_user_id text,
  p_max_daily integer default 3
)
returns json
language plpgsql
security definer
as $$
declare
  v_today date := current_date;
  v_current_count integer := 0;
  v_tomorrow timestamptz := (current_date + interval '1 day')::timestamptz;
begin
  if p_user_id is null or trim(p_user_id) = '' then
    return json_build_object(
      'current_count', 0,
      'limit', p_max_daily,
      'remaining', p_max_daily,
      'reset_at', v_tomorrow
    );
  end if;

  select coalesce(count, 0) into v_current_count
  from public.ai_quiz_usage
  where user_id = p_user_id and usage_date = v_today;

  if not found then
    v_current_count := 0;
  end if;

  return json_build_object(
    'current_count', v_current_count,
    'limit', p_max_daily,
    'remaining', greatest(0, p_max_daily - v_current_count),
    'reset_at', v_tomorrow
  );
end;
$$;

-- ============================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- ============================================================

alter table public.quizzes enable row level security;
alter table public.questions enable row level security;
alter table public.user_results enable row level security;
alter table public.ai_quiz_usage enable row level security;

-- Quizzes RLS
drop policy if exists "Anyone can read quizzes" on public.quizzes;
create policy "Anyone can read quizzes"
  on public.quizzes for select
  using (true);

drop policy if exists "Authenticated users can create quizzes" on public.quizzes;
create policy "Authenticated users can create quizzes"
  on public.quizzes for insert
  to authenticated
  with check (
    created_by = auth.uid()::text 
    or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

drop policy if exists "Admins can update quizzes" on public.quizzes;
create policy "Admins can update quizzes"
  on public.quizzes for update
  to authenticated
  using (
    created_by = auth.uid()::text 
    or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

drop policy if exists "Admins can delete quizzes" on public.quizzes;
create policy "Admins can delete quizzes"
  on public.quizzes for delete
  to authenticated
  using (
    created_by = auth.uid()::text 
    or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

-- Questions RLS
drop policy if exists "Anyone can read questions" on public.questions;
create policy "Anyone can read questions"
  on public.questions for select
  using (true);

drop policy if exists "Authorized users can manage questions" on public.questions;
create policy "Authorized users can manage questions"
  on public.questions for insert
  to authenticated
  with check (true);

drop policy if exists "Admins can delete questions" on public.questions;
create policy "Admins can delete questions"
  on public.questions for delete
  to authenticated
  using (true);

-- User Results RLS
drop policy if exists "Users can read their own quiz results" on public.user_results;
create policy "Users can read their own quiz results"
  on public.user_results for select
  to authenticated
  using (
    user_id = auth.uid()::text
    or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

drop policy if exists "Users can insert their own quiz results" on public.user_results;
create policy "Users can insert their own quiz results"
  on public.user_results for insert
  to authenticated
  with check (user_id = auth.uid()::text);

-- AI Quiz Usage RLS
drop policy if exists "Users can read their own AI quota" on public.ai_quiz_usage;
create policy "Users can read their own AI quota"
  on public.ai_quiz_usage for select
  to authenticated
  using (user_id = auth.uid()::text);

