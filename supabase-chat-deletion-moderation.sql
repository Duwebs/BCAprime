-- ---------- 5) Admin check helper ----------
-- Firebase-uid based: user_profiles.is_admin = true
--                  OR Supabase-auth JWT role = 'admin' (admin panel session).
create or replace function public.is_chat_admin(p_uid text)
returns boolean language sql security definer stable as $$
  select coalesce(
    (select is_admin from public.user_profiles where uid = p_uid limit 1),
    false
  )
  or coalesce(
    (select (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'),
    false
  );
$$;

-- ---------- 6) Ban check + send-guard trigger ----------
create or replace function public.is_chat_banned(p_uid text)
returns boolean language sql security definer stable as $$
  select exists (
    select 1 from public.chat_bans
     where uid = p_uid
       and (expires_at is null or expires_at > now())
  );
$$;

-- Banned sender ka INSERT server par hi reject (client bypass-proof).
create or replace function public.guard_chat_banned_sender()
returns trigger language plpgsql security definer as $$
begin
  if new.uid is not null and new.uid <> '' and public.is_chat_banned(new.uid) then
    raise exception 'You are banned from community chat (%)', new.uid;
  end if;
  return new;
end;
$$;

-- 7a) Sender: "Delete for Everyone" (48h window, tombstone UPDATE).
create or replace function public.bca_soft_delete_message(
  p_id bigint, p_uid text
)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_row public.chat_messages%rowtype;
  v_limit interval := interval '48 hours';
begin
  if p_uid is null or p_uid = '' then
    return jsonb_build_object('ok', false, 'error', 'login-required');
  end if;
  select * into v_row from public.chat_messages where id = p_id;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'not-found');
  end if;
  if v_row.uid <> p_uid then
    return jsonb_build_object('ok', false, 'error', 'not-your-message');
  end if;
  if coalesce(v_row.is_deleted, false) then
    return jsonb_build_object('ok', true, 'already', true);
  end if;
  if v_row.created_at < (now() - v_limit) then
    return jsonb_build_object('ok', false, 'error', 'time-window-expired');
  end if;
  update public.chat_messages
     set body = 'This message was deleted',
         image_url = '', code_lang = '',
         is_deleted = true, deleted_by = 'self',
         deleted_at = now(), deleted_by_uid = p_uid
   where id = p_id;
  insert into public.moderation_logs
    (action, message_id, target_uid, target_name, original_body,
     channel, college, semester, actor_uid)
  values
    ('delete_self', p_id, v_row.uid, v_row.author_name,
     left(coalesce(v_row.body, ''), 2000),
     v_row.channel, coalesce(v_row.college, 'all'), v_row.semester, p_uid);
  return jsonb_build_object('ok', true);
end;
$$;

-- 7b) Admin: delete ANY message (no time limit, admin indicator).
create or replace function public.bca_admin_delete_message(
  p_id bigint, p_uid text, p_reason text default ''
)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_row public.chat_messages%rowtype;
begin
  if p_uid is null or p_uid = '' then
    return jsonb_build_object('ok', false, 'error', 'login-required');
  end if;
  if not public.is_chat_admin(p_uid) then
    return jsonb_build_object('ok', false, 'error', 'admin-only');
  end if;
  select * into v_row from public.chat_messages where id = p_id;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'not-found');
  end if;
  if coalesce(v_row.is_deleted, false) then
    return jsonb_build_object('ok', true, 'already', true);
  end if;
  update public.chat_messages
     set body = 'This message was deleted by an admin',
         image_url = '', code_lang = '',
         is_deleted = true, deleted_by = 'admin',
         deleted_at = now(), deleted_by_uid = p_uid
   where id = p_id;
  insert into public.moderation_logs
    (action, message_id, target_uid, target_name, original_body,
     channel, college, semester, reason, actor_uid)
  values
    ('delete_admin', p_id, v_row.uid, v_row.author_name,
     left(coalesce(v_row.body, ''), 2000),
     v_row.channel, coalesce(v_row.college, 'all'), v_row.semester,
     left(coalesce(p_reason, ''), 500), p_uid);
  return jsonb_build_object('ok', true);
end;
$$;

-- 7c) "Delete for Me" server hide (cross-device) + ban/unban RPCs.
create or replace function public.bca_hide_for_me(
  p_message_id bigint, p_uid text
)
returns boolean
language plpgsql security definer set search_path = public as $$
begin
  if p_uid is null or p_uid = '' or p_message_id is null then
    return false;
  end if;
  insert into public.chat_hides (message_id, uid)
  values (p_message_id, p_uid)
  on conflict (message_id, uid) do nothing;
  return true;
end;
$$;

create or replace function public.bca_ban_user(
  p_uid text, p_target_uid text, p_reason text default '', p_days integer default null
)
returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  if p_uid is null or p_uid = '' then
    return jsonb_build_object('ok', false, 'error', 'login-required');
  end if;
  if not public.is_chat_admin(p_uid) then
    return jsonb_build_object('ok', false, 'error', 'admin-only');
  end if;
  if p_target_uid is null or p_target_uid = '' then
    return jsonb_build_object('ok', false, 'error', 'target-required');
  end if;
  insert into public.chat_bans (uid, reason, banned_by, expires_at)
  values (p_target_uid, left(coalesce(p_reason, ''), 500), p_uid,
          case when p_days is not null and p_days > 0
               then now() + (p_days || ' days')::interval end)
  on conflict (uid) do update
    set reason = excluded.reason,
        banned_by = excluded.banned_by,
        banned_at = now(),
        expires_at = excluded.expires_at;
  insert into public.moderation_logs (action, target_uid, reason, actor_uid)
  values ('ban', p_target_uid, left(coalesce(p_reason, ''), 500), p_uid);
  return jsonb_build_object('ok', true);
end;
$$;

create or replace function public.bca_unban_user(
  p_uid text, p_target_uid text
)
returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  if p_uid is null or p_uid = '' then
    return jsonb_build_object('ok', false, 'error', 'login-required');
  end if;
  if not public.is_chat_admin(p_uid) then
    return jsonb_build_object('ok', false, 'error', 'admin-only');
  end if;
  delete from public.chat_bans where uid = p_target_uid;
  insert into public.moderation_logs (action, target_uid, actor_uid)
  values ('unban', p_target_uid, p_uid);
  return jsonb_build_object('ok', true);
end;
$$;

-- 7d) Backward-compat: purana bca_delete_message -> soft-delete wrapper.
create or replace function public.bca_delete_message(
  p_id bigint, p_uid text
)
returns boolean
language plpgsql security definer set search_path = public as $$
declare
  v_res jsonb;
begin
  if p_uid is null or p_uid = '' then
    return false;
  end if;
  if public.is_chat_admin(p_uid) then
    v_res := public.bca_admin_delete_message(p_id, p_uid, 'legacy client');
  else
    v_res := public.bca_soft_delete_message(p_id, p_uid);
  end if;
  return coalesce((v_res ->> 'ok')::boolean, false);
exception when others then
  return false;
end;
$$;

-- 8) Realtime: ban-guard trigger + chat_bans/moderation_logs live sync.
drop trigger if exists chat_messages_ban_guard on public.chat_messages;
create trigger chat_messages_ban_guard
  before insert on public.chat_messages
  for each row execute function public.guard_chat_banned_sender();

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
     where pubname = 'supabase_realtime'
       and schemaname = 'public' and tablename = 'chat_bans'
  ) then
    alter publication supabase_realtime add table public.chat_bans;
  end if;
  if not exists (
    select 1 from pg_publication_tables
     where pubname = 'supabase_realtime'
       and schemaname = 'public' and tablename = 'moderation_logs'
  ) then
    alter publication supabase_realtime add table public.moderation_logs;
  end if;
end $$;

