-- ---------- 1) Soft-delete columns on chat_messages ----------
alter table public.chat_messages
  add column if not exists is_deleted boolean not null default false;
alter table public.chat_messages
  add column if not exists deleted_by text not null default '';
alter table public.chat_messages
  add column if not exists deleted_at timestamptz;
alter table public.chat_messages
  add column if not exists deleted_by_uid text not null default '';

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'chat_messages_deleted_by_check') then
    alter table public.chat_messages
      add constraint chat_messages_deleted_by_check
      check (deleted_by in ('', 'self', 'admin'));
  end if;
end $$;

create index if not exists chat_messages_is_deleted_idx
  on public.chat_messages (is_deleted);

-- ---------- 2) "Delete for Me" hides (per-user, cross-device) ----------
create table if not exists public.chat_hides (
  message_id bigint not null references public.chat_messages (id) on delete cascade,
  uid text not null default '',
  created_at timestamptz not null default now(),
  constraint chat_hides_unique unique (message_id, uid)
);

create index if not exists chat_hides_uid_idx on public.chat_hides (uid);
create index if not exists chat_hides_message_idx on public.chat_hides (message_id);

alter table public.chat_hides enable row level security;

drop policy if exists "Anyone can read chat hides" on public.chat_hides;
create policy "Anyone can read chat hides"
  on public.chat_hides for select
  to anon, authenticated
  using (true);

-- ---------- 3) Chat bans (remove/ban disruptive users) ----------
create table if not exists public.chat_bans (
  uid text primary key,
  reason text not null default '',
  banned_by text not null default '',
  banned_at timestamptz not null default now(),
  expires_at timestamptz
);

alter table public.chat_bans enable row level security;

drop policy if exists "Anyone can read chat bans" on public.chat_bans;
create policy "Anyone can read chat bans"
  on public.chat_bans for select
  to anon, authenticated
  using (true);

