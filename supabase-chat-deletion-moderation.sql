-- BCAPrime — Community Chat: WHATSAPP-STYLE DELETION + ADMIN MODERATION
-- Run this ONCE in the Supabase SQL Editor.
-- (Sab idempotent hai — dobara run karne par kuch bigadta nahi.
--  Best: pehle supabase-schema.sql + supabase-chat-isolation.sql +
--  supabase-chat-no-phone-gate.sql + supabase-chat-reactions-edits.sql run.)
--
-- Ye file kya karti hai:
--  1) chat_messages par soft-delete columns:
--       is_deleted (bool), deleted_by ('self'|'admin'|''),
--       deleted_at, deleted_by_uid.
--     "Delete for Everyone" ab row DELETE nahi karta — UPDATE karke
--     tombstone banata hai ("This message was deleted" / admin variant)
--     taaki sab clients ko realtime UPDATE event se turant dikhe
--     (bina page reload, bina history gap).
--  2) `chat_hides` table — "Delete for Me" (per-user, cross-device).
--     Local localStorage hides ke SAATH server sync (dusre device par
--     bhi hidden rahe).
--  3) `chat_bans` table + BEFORE INSERT guard trigger — banned user
--     kuch bhej hi nahi sakta (server-side, client bypass-proof).
--  4) `moderation_logs` table — har delete/ban/unban ka audit trail
--     (original text preserved for admin review).
--  5) user_profiles.is_admin — chat-side admin flag (Firebase-uid based,
--     kyunki is stack me Supabase ko Firebase JWT nahi milta).
--  6) SECURITY DEFINER RPCs (same trust model as existing bca_* RPCs):
--       bca_soft_delete_message  — sender: apna msg, 48h window ke andar
--       bca_admin_delete_message — admin: kisi ka bhi msg, no time limit
--       bca_hide_for_me          — Delete for Me (server record)
--       bca_ban_user / bca_unban_user — admin ban controls
--       is_chat_admin / is_chat_banned — helper checks
--  7) Purana bca_delete_message() backward-compat wrapper ban jata hai
--     (soft-delete call karta hai) taaki purane clients na tooten.
-- ============================================================

