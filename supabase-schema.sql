create table if not exists public.resources (
  id bigint generated by default as identity primary key,
  title text not null,
  type text not null check (type in ('notes', 'pyq')),
  subject text not null default 'Community upload',
  college text not null default 'all',
  semester integer not null check (semester between 1 and 6),
  year integer not null check (year between 1 and 3),
  file_name text,
  file_path text,
  file_url text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'archived')),
  downloads integer not null default 0,
  created_at timestamptz not null default now()
);

do $$
begin
  alter table public.resources drop constraint if exists resources_status_check;
  alter table public.resources add constraint resources_status_check
    check (status in ('pending', 'approved', 'rejected', 'archived'));
end $$;

alter table public.resources enable row level security;

-- Track who uploaded each resource so users can see their own upload status.
alter table public.resources add column if not exists uploader_email text not null default '';

drop policy if exists "Anyone can read approved resources" on public.resources;
create policy "Anyone can read resources"
on public.resources for select
using (true);

drop policy if exists "Anyone can submit pending resources" on public.resources;
create policy "Anyone can submit pending resources"
on public.resources for insert
to anon, authenticated
with check (status = 'pending');

-- NOTE: Temporary open-moderation policies so the direct admin bypass
-- (admin.html hard-coded login) can approve/reject/delete without a
-- Supabase session. Remove these two policies once you log in with a
-- real Supabase admin account (app_metadata.role = 'admin').
drop policy if exists "Temporary: open moderation for direct admin bypass" on public.resources;
create policy "Temporary: open moderation for direct admin bypass"
on public.resources for update
to anon, authenticated
using (true)
with check (true);

drop policy if exists "Temporary: open delete for direct admin bypass" on public.resources;
create policy "Temporary: open delete for direct admin bypass"
on public.resources for delete
to anon, authenticated
using (true);

drop policy if exists "Authenticated admins can manage resources" on public.resources;
create policy "Authenticated admins can manage resources"
on public.resources for all
to authenticated
using (auth.jwt() -> 'app_metadata' ->> 'role' = 'admin')
with check (auth.jwt() -> 'app_metadata' ->> 'role' = 'admin');

insert into storage.buckets (id, name, public)
